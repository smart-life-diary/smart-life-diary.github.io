def count(s):
    """フォームのカウンターに合わせて、改行を数えない。"""
    return len(s.replace("\n", ""))


def h(label, s, lim):
    n = count(s)
    flag = "" if n <= lim else "　**←上限超え**"
    return f"**{label}（{n}／{lim}）{flag}**"


def block(s):
    return "```\n" + s + "\n```"


